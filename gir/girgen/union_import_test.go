package girgen_test

import (
	"strings"
	"testing"
)

// unionNoRecordFieldsFixture declares a union with a copy() method whose only
// field is a plain gpointer — not a record, enum, or bitfield. The union
// generator's CastBlock always emits runtime.SetFinalizer, but the "runtime"
// import used to be added only inside the per-field loop, which skips
// non-record fields entirely: a union like this generated code referencing
// runtime without importing it.
const unionNoRecordFieldsFixture = `<?xml version="1.0"?>
<repository version="1.2"
            xmlns="http://www.gtk.org/introspection/core/1.0"
            xmlns:c="http://www.gtk.org/introspection/c/1.0"
            xmlns:glib="http://www.gtk.org/introspection/glib/1.0">
  <namespace name="Test"
             version="1.0"
             c:identifier-prefixes="Test"
             c:symbol-prefixes="test"
             shared-library="libtest.so">
    <union name="Value"
           c:type="TestValue"
           glib:type-name="TestValue"
           glib:get-type="test_value_get_type">
      <field name="data" writable="1">
        <type name="gpointer" c:type="gpointer"/>
      </field>
      <method name="copy" c:identifier="test_value_copy">
        <return-value transfer-ownership="full">
          <type name="Test.Value" c:type="TestValue*"/>
        </return-value>
        <parameters>
          <instance-parameter name="value" transfer-ownership="none">
            <type name="Test.Value" c:type="TestValue*"/>
          </instance-parameter>
        </parameters>
      </method>
      <method name="free" c:identifier="test_value_free">
        <return-value transfer-ownership="none">
          <type name="none" c:type="void"/>
        </return-value>
        <parameters>
          <instance-parameter name="value" transfer-ownership="none">
            <type name="Test.Value" c:type="TestValue*"/>
          </instance-parameter>
        </parameters>
      </method>
    </union>
  </namespace>
</repository>`

// TestUnionRuntimeImport asserts that a generated union whose CastBlock uses
// runtime.SetFinalizer also imports "runtime", even when no field goes through
// the per-field conversion loop (the only other place the import was added).
func TestUnionRuntimeImport(t *testing.T) {
	src := generateNamespace(t, unionNoRecordFieldsFixture, "Test", "1.0")

	// Sanity: the union and its finalizer-using copy block must be emitted, so
	// the import assertion below can't pass vacuously.
	if !strings.Contains(src, "type Value struct") {
		t.Skipf("union Value not generated by this fixture; got:\n%s", src)
	}
	if !strings.Contains(src, "runtime.SetFinalizer") {
		t.Fatalf("expected the union copy block to use runtime.SetFinalizer; got:\n%s", src)
	}

	if !strings.Contains(src, "\"runtime\"") {
		t.Errorf("generated union uses runtime.SetFinalizer without importing \"runtime\":\n%s", src)
	}
}
